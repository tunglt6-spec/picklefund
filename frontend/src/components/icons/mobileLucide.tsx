/** Preserve the original icon on desktop and outside the authenticated app. */
function mobileIcon(Original: LucideIcon, name: PlayfulIconName): LucideIcon {
  const Icon = forwardRef<SVGSVGElement, LucideProps>((props, ref) => {
    const mobile = useContext(MobileIconContext)
    return mobile ? <PlayfulIcon ref={ref} {...props} name={name} /> : <Original ref={ref} {...props} />
  })
  Icon.displayName = `Playful(${name})`
  return Icon
}
